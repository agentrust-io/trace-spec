// Compile the repository's JSON Schemas into standalone ES modules.
//
// Run by `npm run build`. The output, src/generated/validators.js and
// block-validator.js, is not committed: it is derived from the schema files on
// every build, so it cannot drift from them. TRACE_SCHEMA_DIR selects another
// schema directory, which is how the package is built against a released
// schema set for comparison.

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { _ } from "ajv";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(process.env.TRACE_SCHEMA_DIR ?? join(here, "..", "..", "schema"));
const files = [
  "trace-claim.json",
  "trace-revocation-bundle.json",
  "trace-revocation.json",
  "behavior-trace-block-experimental-v1.json",
];

const texts = Object.fromEntries(files.map((name) => [name, readFileSync(join(schemaDir, name), "utf8")]));
const schemas = Object.fromEntries(files.map((name) => [name, JSON.parse(texts[name])]));
const digests = Object.fromEntries(
  files.map((name) => [name, createHash("sha256").update(readFileSync(join(schemaDir, name))).digest("hex")]),
);

const BLOCK = "behavior-trace-block-experimental-v1.json";

// The record and bundle validators report every violation, so they collect all
// errors. The block validator is only a yes or no, and it holds the one
// uniqueItems: with allErrors it would compare every pair of an array that
// already failed maxItems, so it stops at the first failure instead.
const options = (allErrors) => ({
  allErrors,
  // The signature pre-image is built from a record's own members, so the
  // schema must judge the same members: `required` and `properties` test own
  // properties and every object walk uses Object.keys, never for-in. An
  // inherited member, cross-realm or not, is absent to both.
  ownProperties: true,
  // The schemas use if/then without a sibling "type" and union types in
  // canonicalizableValue; both are ordinary Draft 2020-12 and not errors.
  strict: true,
  strictTypes: false,
  strictRequired: false,
  allowUnionTypes: true,
  validateFormats: true,
  // A placeholder at compile time; the generated code calls the real checker
  // through the __formats binding imported below.
  formats: { uri: () => true },
  code: { source: true, esm: true, formats: _`__formats` },
});

const UCS2 = 'require("ajv/dist/runtime/ucs2length").default';
const EQUAL = 'require("ajv/dist/runtime/equal").default';

/** Standalone ES module code exporting a validator for each named schema file. */
function compile(names, allErrors, exported) {
  const ajv = new Ajv2020.default({ schemas: names.map((name) => schemas[name]), ...options(allErrors) });
  let code = standaloneCode.default(
    ajv,
    Object.fromEntries(Object.entries(exported).map(([fn, name]) => [fn, schemas[name].$id])),
  );
  code = code.split(UCS2).join("__codePointLength");
  code = code.split(EQUAL).join("__jsonEqual");
  code = code.replace(/^"use strict";/, "");
  if (/\brequire\(/.test(code)) {
    const found = code.match(/require\([^)]*\)/g);
    throw new Error(`generated validators still require a runtime module: ${found.join(", ")}`);
  }
  return code;
}

const code = compile(files.filter((name) => name !== BLOCK), true, {
  validateRecord: "trace-claim.json",
  validateBundle: "trace-revocation-bundle.json",
});
const blockCode = compile([BLOCK], false, { validateBlock: BLOCK });

const BANNER = [
  "// Generated by scripts/generate-validators.mjs from the schema files named in",
  "// schemaDigests (validators.js). Do not edit; run `npm run build`.",
];

/** Imports of the runtime helpers *source* uses. */
function imports(source) {
  const text = ["codePointLength", "jsonEqual"].filter((name) => source.includes(`__${name}`));
  return [
    ...(source.includes("__formats") ? ['import { formats as __formats } from "../uri.js";'] : []),
    ...(text.length ? [`import { ${text.map((name) => `${name} as __${name}`).join(", ")} } from "../text.js";`] : []),
  ];
}
const header = [...BANNER, ...imports(code), `export const schemaDigests = ${JSON.stringify(digests)};`, ""].join("\n");

const outDir = join(here, "..", "src", "generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "validators.js"), `${header}${code}\n`);
writeFileSync(join(outDir, "block-validator.js"), `${[...BANNER, ...imports(blockCode), ""].join("\n")}${blockCode}\n`);
writeFileSync(
  join(outDir, "validators.d.ts"),
  [
    "// Generated by scripts/generate-validators.mjs. Do not edit.",
    "export declare const schemaDigests: Readonly<Record<string, string>>;",
    "export declare function validateRecord(data: unknown): boolean;",
    "export declare function validateBundle(data: unknown): boolean;",
    "",
  ].join("\n"),
);
writeFileSync(
  join(outDir, "block-validator.d.ts"),
  [
    "// Generated by scripts/generate-validators.mjs. Do not edit.",
    "export declare function validateBlock(data: unknown): boolean;",
    "",
  ].join("\n"),
);
console.log(`validators generated from ${schemaDir}`);
