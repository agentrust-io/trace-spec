// Compile the repository's JSON Schemas into a standalone ES module.
//
// Run by `npm run build`. The output, src/generated/validators.js, is not
// committed: it is derived from the schema files on every build, so it cannot
// drift from them. TRACE_SCHEMA_DIR selects another schema directory, which is
// how the package is built against a released schema set for comparison.

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { _ } from "ajv";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(process.env.TRACE_SCHEMA_DIR ?? join(here, "..", "..", "schema"));
const files = ["trace-claim.json", "trace-revocation-bundle.json", "trace-revocation.json"];

const texts = Object.fromEntries(files.map((name) => [name, readFileSync(join(schemaDir, name), "utf8")]));
const schemas = Object.fromEntries(files.map((name) => [name, JSON.parse(texts[name])]));
const digests = Object.fromEntries(
  files.map((name) => [name, createHash("sha256").update(readFileSync(join(schemaDir, name))).digest("hex")]),
);

const ajv = new Ajv2020.default({
  schemas: files.map((name) => schemas[name]),
  allErrors: true,
  // The schemas use if/then without a sibling "type" and union types in
  // canonicalizableValue; both are ordinary Draft 2020-12 and not errors.
  strict: true,
  strictTypes: false,
  strictRequired: false,
  allowUnionTypes: true,
  validateFormats: true,
  // A placeholder at compile time; the generated code calls the real checker
  // through the __formats binding imported below.
  formats: { uri: () => true },
  code: { source: true, esm: true, formats: _`__formats` },
});

let code = standaloneCode.default(ajv, {
  validateRecord: schemas["trace-claim.json"].$id,
  validateBundle: schemas["trace-revocation-bundle.json"].$id,
});

const UCS2 = 'require("ajv/dist/runtime/ucs2length").default';
code = code.split(UCS2).join("__codePointLength");
code = code.replace(/^"use strict";/, "");
if (/\brequire\(/.test(code)) {
  const found = code.match(/require\([^)]*\)/g);
  throw new Error(`generated validators still require a runtime module: ${found.join(", ")}`);
}

const header = [
  "// Generated by scripts/generate-validators.mjs from the schema files named in",
  "// schemaDigests. Do not edit; run `npm run build`.",
  'import { formats as __formats } from "../uri.js";',
  'import { codePointLength as __codePointLength } from "../text.js";',
  `export const schemaDigests = ${JSON.stringify(digests)};`,
  "",
].join("\n");

const outDir = join(here, "..", "src", "generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "validators.js"), `${header}${code}\n`);
writeFileSync(
  join(outDir, "validators.d.ts"),
  [
    "// Generated by scripts/generate-validators.mjs. Do not edit.",
    "export declare const schemaDigests: Readonly<Record<string, string>>;",
    "export declare function validateRecord(data: unknown): boolean;",
    "export declare function validateBundle(data: unknown): boolean;",
    "",
  ].join("\n"),
);
console.log(`validators generated from ${schemaDir}`);
