// --- Self-check every fixture against the manifest before writing ---
const verifySig = (env, pubHex) => {
  try { return ed25519.verify(hexToBytes(env.signature.sig), canonicalBytes(env.payload), hexToBytes(pubHex)); }
  catch { return false; }
};
let failures = 0;
for (const [name, env] of Object.entries(fixtures)) {
  const exp = expected.results[name];
  const sig = verifySig(env, SIGNER_PUB) ? 'pass' : 'fail';
  let ok = sig === exp.signature;
  let chain = 'n/a';
  if (expected.chain[name]) {
    const pred = fixtures[expected.chain[name]];
    const link = env.payload.previousReceiptHash;
    // Either encoding of the whole-envelope hash (bare hex in 02 and 04).
    chain = link === envelopeHash(pred) || link === chainLink(pred) ? 'pass' : 'fail';
    ok = ok && chain === exp.chain;
  }
  // structural conformance
  ok = ok && env.signature.alg === 'EdDSA'
          && /^[0-9a-f]{128}$/.test(env.signature.sig)
          && env.payload.issuer_id === env.signature.kid
          && env.payload.type === 'protectmcp:decision'
          // require_approval is the revision 03 addition (s3.1.1)
          && ['allow', 'deny', 'rate_limit', 'require_approval'].includes(env.payload.decision);
  // Revision 03 s6.7: the link MUST be "sha256:" and 64 lowercase hex digits.
  if (REVISION_03.has(name) && 'previousReceiptHash' in env.payload) {
    ok = ok && /^sha256:[0-9a-f]{64}$/.test(env.payload.previousReceiptHash);
  }
  console.log(`${name}: signature=${sig} chain=${chain} structural=${ok ? 'ok' : 'BAD'}`);
  if (!ok) failures++;
}
// The remaining columns are recomputed for EVERY fixture and compared with the
// manifest, not only for the fixture meant to fail each one: asserting the
// failure alone passes whether one fixture is stale or all of them are, which
// is how the six revision 02 fixtures once shared one policy_digest while four
// were declared fresh. The loop also refuses an issued_at within a day of
// either end of the key window. 03's signature fails, so the columns that read
// claims in its payload are n/a and skipped.
const DAY_MS = 24 * 60 * 60 * 1000;
const [windowFrom, windowUntil] = [KEY_VALID_FROM, KEY_VALID_UNTIL].map(Date.parse);
for (const [name, env] of Object.entries(fixtures)) {
  const exp = expected.results[name];
  const issued = Date.parse(env.payload.issued_at);
  if (Math.min(Math.abs(issued - windowFrom), Math.abs(issued - windowUntil)) < DAY_MS) {
    console.error(`${name}: issued_at is within a day of an end of the key window`);
    failures++;
  }
  for (const [axis, actual] of [
    ['policy_freshness', env.payload.policy_digest === expected.current_policy_digest ? 'pass' : 'fail'],
    ['session_binding', env.payload.session_id === expected.expected_session_id ? 'pass' : 'fail'],
    ['signing_input', 'signature' in env.payload ? 'fail' : 'pass'],
    ['key_window', windowFrom <= issued && issued < windowUntil ? 'pass' : 'fail'],
  ]) {
    if (exp[axis] === 'n/a') continue;
    if (actual !== exp[axis]) {
      console.error(`${name}: ${axis} is ${actual}, manifest declares ${exp[axis]}`);
      failures++;
    }
  }
}
if (failures) { console.error('SELF-CHECK FAILED'); process.exit(1); }

mkdirSync('out', { recursive: true });
for (const [name, env] of Object.entries(fixtures)) {
  writeFileSync(`out/${name}`, JSON.stringify(env, null, 2) + '\n');
}
writeFileSync('out/expected.json', JSON.stringify(expected, null, 2) + '\n');
writeFileSync('out/acta-keys.json', JSON.stringify(keySet, null, 2) + '\n');
writeFileSync('out/signer-public-key.txt', SIGNER_PUB + '\n');
writeFileSync('out/mismatched-signer-public-key.txt', MISMATCH_PUB + '\n');
console.log(`\nkid: ${KID}`);
console.log(`chain head (02, s5.7 envelope hash): ${envelopeHash(r02)}`);
console.log(`wrote ${Object.keys(fixtures).length} fixtures + expected.json + acta-keys.json + 2 public keys to out/`);
